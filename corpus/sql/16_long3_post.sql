-- R-040, step 3: the truth file for T_LONG3 (TO_LOB copy, then the lengths and the first and last 20 bytes). Run as CORPUS.

SET ECHO OFF
SET TERMOUT OFF
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
SET LINESIZE 32767
SET TRIMSPOOL ON
SET VERIFY OFF
SET DEFINE OFF
SET SQLBLANKLINES ON
SET LONG 100000
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE TABLE t_long3_chk AS SELECT id, TO_LOB(l) c, v FROM t_long3;
SPOOL /fixtures/truth_long3.txt
SELECT id || '|' || DBMS_LOB.GETLENGTH(c) || '|' || RAWTOHEX(UTL_RAW.CAST_TO_RAW(DBMS_LOB.SUBSTR(c, 20, 1)))
       || '|' || RAWTOHEX(UTL_RAW.CAST_TO_RAW(DBMS_LOB.SUBSTR(c, 20, DBMS_LOB.GETLENGTH(c) - 19))) || '|' || v
  FROM t_long3_chk ORDER BY id;
SPOOL OFF
DROP TABLE t_long3_chk PURGE;
EXIT
