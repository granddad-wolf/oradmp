-- 07_ru_setup.sql: run as SYSTEM. Creates the user CORPUS_RU (drops it first if it exists).
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE
BEGIN
  EXECUTE IMMEDIATE 'DROP USER corpus_ru CASCADE';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -1918 THEN RAISE; END IF;
END;
/
CREATE USER corpus_ru IDENTIFIED BY "Corpus_ru_1" DEFAULT TABLESPACE users TEMPORARY TABLESPACE temp QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW TO corpus_ru;
EXIT
