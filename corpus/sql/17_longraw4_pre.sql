SET ECHO OFF
SET TERMOUT OFF
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
SET LINESIZE 32767
SET TRIMSPOOL ON
SET VERIFY OFF
SET DEFINE OFF
SET SQLBLANKLINES ON
SET LONG 100000
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

DECLARE n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'T_FRAME';
  IF n <> 1 THEN RAISE_APPLICATION_ERROR(-20001, 'T_FRAME is missing'); END IF;
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN ('T_LONGRAW4','T_LONGRAW4_CHK')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE "' || t.table_name || '" PURGE';
  END LOOP;
END;
/
CREATE TABLE t_longraw4 (id NUMBER(3), lr LONG RAW);
EXIT
