#[test]
fn d_composite_partition_lines_out_of_order_give_one_untested_layout_warning_and_the_parts_are_read(
) {
    let file = "18c/part2_exp_18c.dmp";
    let good = bytes_of(file);
    let r = walk_bytes(good.clone()).unwrap();
    assert!(r.warnings.is_empty());
    let rows = |r: &WalkReport| {
        r.sections[0]
            .parts
            .iter()
            .map(|p| p.rows.rows)
            .collect::<Vec<_>>()
    };
    assert_eq!(rows(&r), [21, 29, 0, 0, 21, 29]);
    let com1 = find_bytes(&good, b"\nCOMPARTITION \"P1\"\n") + 1;
    let com2 = find_bytes(&good, b"\nCOMPARTITION \"P_EMPTY\"\n") + 1;
    let end1 = find_bytes(&good, b"\nENDCOMPARTITION\n") + 1;

    let check = |b: Vec<u8>, at: usize, what: &str| {
        let r = walk_bytes(b).unwrap_or_else(|e| panic!("{what}: {e}"));
        assert!(matches!(r.end, WalkEnd::Complete), "{what}");
        assert_eq!(warning_codes(&r), [WarningCode::UntestedLayout], "{what}");
        assert_eq!(r.warnings[0].offset, Some(at as u64), "{what}");
        assert_eq!(r.warnings[0].table, Some(1), "{what}");
        assert_eq!(
            rows(&r),
            [21, 29, 0, 0, 21, 29],
            "{what}: the parts are read"
        );
        // none of the five lines became a G1 candidate or took a field
        assert_eq!(r.item_counts.g1_fields, 0, "{what}");
    };

    // SUBPARTITION with no open COMPARTITION (inserted before the first COMPARTITION)
    let mut b = good.clone();
    insert_keeping_size(&mut b, com1, b"SUBPARTITION \"ZZ\"\n");
    check(b, com1, "SUBPARTITION with no open COMPARTITION");

    // a missing ENDCOMPARTITION: the first one is not a line of the five, the next COMPARTITION arrives
    // while one is open (the warning stands at that line)
    let mut b = good.clone();
    b[end1] = b'X';
    check(b, com2, "missing ENDCOMPARTITION");

    // ENDPARTITION inside a COMPARTITION (inserted behind the COMPARTITION line of the first one)
    let mut b = good.clone();
    let sub1 = find_bytes(&good, b"\nSUBPARTITION \"SYS_SUBP368\"\n") + 1;
    insert_keeping_size(&mut b, sub1, b"ENDPARTITION\n");
    check(b, sub1, "ENDPARTITION inside a COMPARTITION");

    // PARTITION and COMPARTITION in one section: the warning stands at the COMPARTITION line
    let mut b = good.clone();
    insert_keeping_size(&mut b, com1, b"PARTITION \"ZZ\"\n");
    check(
        b,
        com1 + b"PARTITION \"ZZ\"\n".len(),
        "PARTITION and COMPARTITION",
    );

    // ENDCOMPARTITION with none open
    let mut b = good.clone();
    insert_keeping_size(&mut b, com1, b"ENDCOMPARTITION\n");
    check(b, com1, "ENDCOMPARTITION with none open");

    // ENDCOMPARTITION of a COMPARTITION that has no part: a COMPARTITION line and its ENDCOMPARTITION
    // inserted between two compartitions; the warning stands at the ENDCOMPARTITION
    let mut b = good.clone();
    let ins = b"COMPARTITION \"ZZ\"\nENDCOMPARTITION\n";
    insert_keeping_size(&mut b, com2, ins);
    check(
        b,
        com2 + b"COMPARTITION \"ZZ\"\n".len(),
        "ENDCOMPARTITION without a part",
    );

    // a section with naming lines that ends without ENDPARTITION: the section ends at TABLE "T_FRAME"
    let mut b = good.clone();
    let endp = find_bytes(&good, b"\nENDPARTITION\n") + 1;
    b[endp] = b'X';
    let tframe = find_bytes(&good, b"\nTABLE \"T_FRAME\"") + 1;
    check(b, tframe, "no ENDPARTITION");
}

#[test]
fn d_a_second_insert_into_without_a_naming_line_is_framing_and_without_a_direct_one_a_warning() {
    let file = "18c/part2_exp_18c.dmp";
    let good = bytes_of(file);
    let r = walk_bytes(good.clone()).unwrap();
    let second = r.sections[0].parts[1].insert_offset;
    // no COMPARTITION and no SUBPARTITION line is a line of the five any more: Framing at the 2nd INSERT
    let mut b = good.clone();
    for pat in [&b"\nCOMPARTITION \""[..], b"\nSUBPARTITION \""] {
        let mut from = 0;
        while let Some(i) = b[from..].windows(pat.len()).position(|w| w == pat) {
            b[from + i + 1] = b'X';
            from += i + 1;
        }
    }
    let e = walk_bytes(b).unwrap_err();
    assert_eq!(
        (e.code, e.offset, e.table),
        (ErrorCode::Framing, Some(second), Some(1))
    );
    // only the SUBPARTITION lines renamed: COMPARTITION is not a naming line either: Framing
    let mut b = good.clone();
    let mut from = 0;
    while let Some(i) = b[from..]
        .windows(15)
        .position(|w| w == b"\nSUBPARTITION \"")
    {
        b[from + i + 1] = b'X';
        from += i + 1;
    }
    let e = walk_bytes(b).unwrap_err();
    assert_eq!((e.code, e.offset), (ErrorCode::Framing, Some(second)));
    // a naming line was seen but does not directly precede the INSERT INTO: read, warned, named after the
    // last naming line (the SUBPARTITION line of the second part renamed)
    let mut b = good.clone();
    let sub = find_bytes(&good, b"\nSUBPARTITION \"SYS_SUBP369\"\n") + 1;
    b[sub] = b'X';
    let r = walk_bytes(b).unwrap();
    assert_eq!(warning_codes(&r), [WarningCode::UntestedLayout]);
    assert_eq!(r.warnings[0].offset, Some(second));
    let p = &r.sections[0].parts[1];
    assert_eq!(p.subpartition.as_ref().unwrap().name_raw, b"SYS_SUBP368");
    assert_eq!(p.partition.as_ref().unwrap().name_raw, b"P1");
}

