/// `truth_part2.txt`: `SP|<partition>|<subpartition>` six times, in file order; `ROW|n|<subpartition>` 100
/// times. Expected row counts per subpartition: 21, 29, 0, 0, 21, 29 (plan T-3c (c)).
fn truth_part2() -> (Vec<(String, String)>, Vec<u64>) {
    let t = common::truth_text("18c", "truth_part2.txt");
    let mut sp = Vec::new();
    let mut rows: Vec<String> = Vec::new();
    for l in t.lines() {
        let f: Vec<&str> = l.split('|').collect();
        match f[0] {
            "SP" => sp.push((f[1].to_string(), f[2].to_string())),
            "ROW" => rows.push(f[2].to_string()),
            _ => {}
        }
    }
    let counts = sp
        .iter()
        .map(|(_, s)| rows.iter().filter(|r| *r == s).count() as u64)
        .collect();
    (sp, counts)
}

#[test]
fn c_part2_is_one_section_with_six_parts_named_as_the_truth_file() {
    let (sp, truth_rows) = truth_part2();
    assert_eq!(sp.len(), 6);
    // by the order of the SP lines (sorted by name): P1 x2, P3 x2, P_EMPTY x2
    assert_eq!(
        truth_rows,
        [21, 29, 21, 29, 0, 0],
        "the plan's counts, from the truth file"
    );
    for (file, direct) in [
        ("18c/part2_exp_18c.dmp", false),
        ("18c/part2_exp_direct_18c.dmp", true),
    ] {
        let options = WalkOptions {
            record_items: true,
            ..WalkOptions::default()
        };
        let r = walk_rel(file, &options);
        assert!(matches!(r.end, WalkEnd::Complete), "{file}");
        assert!(r.warnings.is_empty(), "{file}: {:?}", r.warnings);
        assert_eq!(names(&r), ["T_PART2", "T_FRAME"], "{file}");
        let s = &r.sections[0];
        assert!(s.partitioned && s.subpartitioned, "{file}");
        assert_eq!(s.parts.len(), 6, "{file}");
        let named: Vec<(String, String)> = s
            .parts
            .iter()
            .map(|p| {
                (
                    String::from_utf8(p.partition.as_ref().unwrap().name_raw.clone()).unwrap(),
                    String::from_utf8(p.subpartition.as_ref().unwrap().name_raw.clone()).unwrap(),
                )
            })
            .collect();
        // the SP lines of the truth file are sorted by name, the file is in partition order (P1,
        // P_EMPTY, P3): same six pairs, and the rows of each part are the ROW lines of its subpartition
        let mut sorted = named.clone();
        sorted.sort();
        let mut truth_sorted = sp.clone();
        truth_sorted.sort();
        assert_eq!(sorted, truth_sorted, "{file}");
        let rows: Vec<u64> = s.parts.iter().map(|p| p.rows.rows).collect();
        assert_eq!(rows, [21, 29, 0, 0, 21, 29], "{file}");
        let per_name = |n: &(String, String)| truth_rows[sp.iter().position(|x| x == n).unwrap()];
        assert_eq!(
            rows,
            named.iter().map(per_name).collect::<Vec<_>>(),
            "{file}"
        );
        // the two empty subpartitions: [E2] on the direct path (no `ff ff`), [E1] otherwise
        for i in [2usize, 3] {
            let want = if direct {
                EndMarker::LfOnly
            } else {
                EndMarker::FfFf
            };
            assert_eq!(s.parts[i].rows.end_marker, want, "{file} part {i}");
            assert!(!s.parts[i].rows.e2a_no_rows);
        }
        assert!(s
            .parts
            .iter()
            .all(|p| p.header.same_layout(&s.parts[0].header)));
        // the 16 ANALSTATS items stand after the last ENDCOMPARTITION and before ENDPARTITION, and are
        // skipped without a warning
        let b = bytes_of(file);
        let last_end = s.parts[5].rows.rows_end_offset;
        let endpartition = u64::try_from(find_bytes(&b, b"\nENDPARTITION") + 1).unwrap();
        let stats_lines = r
            .items
            .iter()
            .filter(|i| i.offset >= last_end && i.offset < endpartition)
            .filter(|i| {
                matches!(i.kind, oradmp_core::exp::items::ItemKind::Line)
                    && b[usize::try_from(i.offset).unwrap()..].starts_with(b"ANALSTATS ")
            })
            .count();
        assert_eq!(stats_lines, 16, "{file}");
        assert_eq!(
            r.sections[1].parts[0].rows.rows, 7,
            "T_FRAME follows ({file})"
        );
    }
}

