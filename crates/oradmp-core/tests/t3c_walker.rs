// (d) a synthetic long LOB value with a total of 0, and AQ-1
// ---------------------------------------------------------------------------------------------

/// ADR-23 (owner): the first long value of T_LOB (`lob_exp_18c.dmp`: `fc ff`, T = 200,000, 13 chunks) is
/// replaced by `fc ff` and 8 zero bytes: the value frames (no chunk), and the walker warns at the `fc ff`,
/// because no fixture holds such a value (AQ-1: 0 in the fixture files, `x_the_exp_fixtures...` in `t3a_walker.rs`).
#[test]
fn d_a_long_lob_value_with_a_total_of_zero_is_read_with_an_untested_layout_warning() {
    let file = "18c/lob_exp_18c.dmp";
    let good = bytes_of(file);
    let options = WalkOptions {
        record_lob: true,
        ..WalkOptions::default()
    };
    let r = walk_rel(file, &options);
    let part = &r.sections[0].parts[0];
    let detail = part.rows.lob_detail.as_ref().unwrap();
    let v = detail
        .values
        .iter()
        .find(|v| v.form == oradmp_core::exp::rows::LobForm::Long)
        .unwrap();
    let start = usize::try_from(v.offset).unwrap();
    let len = 2 + 8 + v.chunks.iter().map(|c| 2 + usize::from(*c)).sum::<usize>();
    assert_eq!(good[start..start + 2], [0xfc, 0xff]);
    let mut b = good[..start].to_vec();
    b.extend_from_slice(&[0xfc, 0xff, 0, 0, 0, 0, 0, 0, 0, 0]);
    b.extend_from_slice(&good[start + len..]);
    b.extend(std::iter::repeat_n(0u8, len - 10)); // same size: no W-FILE-SIZE
    let r = walk(Cursor::new(b), &options).unwrap();
    assert!(matches!(r.end, WalkEnd::Complete));
    assert_eq!(warning_codes(&r), [WarningCode::UntestedLayout]);
    let w = &r.warnings[0];
    assert_eq!(
        (w.offset, w.table, w.row, w.column, w.length),
        (
            Some(v.offset),
            Some(1),
            Some(v.row),
            Some(v.column),
            Some(0)
        )
    );
    let p = &r.sections[0].parts[0];
    let z = p.rows.lob_zero_total.unwrap();
    assert_eq!((z.offset, z.row, z.column), (v.offset, v.row, v.column));
    // the value count is unchanged and the walk reaches the end
    assert_eq!(p.rows.lob.values, part.rows.lob.values);
    assert_eq!(p.rows.lob.long, part.rows.lob.long);
    assert_eq!(
        p.rows.lob.stored_bytes,
        part.rows.lob.stored_bytes - v.total
    );
}

// ---------------------------------------------------------------------------------------------
// (e) a synthetic single-column direct-path LONG table: the three outcomes of ADR-22
// ---------------------------------------------------------------------------------------------

/// A copy of `t_empty_exp_direct_18c.dmp` (header, one table section, trailer) whose table section is
/// replaced by `T_ONE` with the single column `L` of type `code` (8 LONG, 24 LONG RAW) on the direct path;
/// `rows` is what stands between the path flag and the next item (see the callers). The size is padded to a
/// multiple of RECORDLENGTH (8192) with zeros.
fn single_column_file(code: u16, rows: &[u8]) -> Vec<u8> {
    let d = bytes_of("18c/t_empty_exp_direct_18c.dmp");
    let from = find_bytes(&d, b"TABLE \"T_EMPTY\"\n");
    let to = find_bytes(&d, b"METRICSTreferential");
    let ty = if code == 8 { "LONG" } else { "LONG RAW" };
    let mut b = d[..from].to_vec();
    b.extend_from_slice(b"TABLE \"T_ONE\"\n");
    b.extend_from_slice(
        format!(
            "CREATE TABLE \"T_ONE\" (\"L\" {ty})  PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255 \
             TABLESPACE \"USERS\" LOGGING NOCOMPRESS\n"
        )
        .as_bytes(),
    );
    b.extend_from_slice(b"INSERT INTO \"T_ONE\" (\"L\") VALUES (:1)\n");
    b.extend_from_slice(&1u16.to_le_bytes()); // one column
    b.extend_from_slice(&code.to_le_bytes());
    b.extend_from_slice(&0u16.to_le_bytes()); // descriptor length 0 [T5]
    b.extend_from_slice(&[0, 0, 1, 0]); // m = 0, path flag 1
    b.extend_from_slice(rows);
    let tail_end = d.iter().rposition(|&x| x != 0).unwrap() + 1;
    b.extend_from_slice(&d[to..tail_end]);
    while !b.len().is_multiple_of(8192) {
        b.push(0);
    }
    b
}

fn row_value(piece_lens: &[u16], fill: u8) -> Vec<u8> {
    let mut v = Vec::new();
    for (i, n) in piece_lens.iter().enumerate() {
        let more = i + 1 < piece_lens.len();
        let u = if more { n | 0x8000 } else { *n };
        v.extend_from_slice(&u.to_le_bytes());
        v.extend(std::iter::repeat_n(fill, usize::from(*n)));
    }
    v
}

#[test]
fn e_a_single_column_direct_path_long_table_has_the_three_outcomes_of_adr_22() {
    let strict = WalkOptions {
        strict_e2a: true,
        ..WalkOptions::default()
    };
    for code in [8u16, 24] {
        // the synthetic file is itself well formed: a one-row table with a value that is plainly a row
        let plain = single_column_file(code, &{
            let mut r = row_value(&[3], b'a');
            r.extend_from_slice(&[0xff, 0xff, b'\n']);
            r
        });
        let r = walk_bytes(plain).unwrap();
        assert!(matches!(r.end, WalkEnd::Complete), "{code}");
        assert!(r.warnings.is_empty(), "{code}: {:?}", r.warnings);
        assert_eq!(r.sections[0].parts[0].rows.rows, 1);

        // outcome 1: empty, `LF` and then a line of a known kind (METRICST...): no rows,
        // W-UNTESTED-LAYOUT at the LF, no `ff ff`
        let empty = single_column_file(code, b"\n");
        let r = walk_bytes(empty.clone()).unwrap();
        assert!(matches!(r.end, WalkEnd::Complete), "{code}");
        let p = &r.sections[0].parts[0];
        assert_eq!(
            (p.rows.rows, p.rows.end_marker),
            (0, EndMarker::LfOnly),
            "{code}"
        );
        assert!(p.rows.e2a_no_rows);
        assert_eq!(warning_codes(&r), [WarningCode::UntestedLayout], "{code}");
        assert_eq!(r.warnings[0].offset, Some(p.rows.end_marker_offset));
        assert_eq!(r.warnings[0].table, Some(1));
        assert_eq!(r.empty_tables(), (1, 0));
        // outcome 3: strict, "text follows" alone is Framing
        let e = walk(Cursor::new(empty), &strict).unwrap_err();
        assert_eq!(
            (e.code, e.offset, e.table),
            (ErrorCode::Framing, Some(p.rows.end_marker_offset), Some(1)),
            "{code}"
        );

        // outcome 2: rows. Values: NULL; a value of 10 bytes (`0a 00 ...`: an LF as the first byte, and a
        // second byte that is no capital letter); a chain of 2 pieces totalling 32,001 bytes (one above the
        // limit); a value of 0x410a bytes (`0a 41`: LF and a capital letter, "text follows" fails because
        // the line is no item of a known kind). The first row is the LF-first one.
        let mut rows = row_value(&[10], b'x');
        rows.extend_from_slice(&[0xfe, 0xff]);
        rows.extend(row_value(&[16_000, 16_001], b'y'));
        rows.extend(row_value(&[0x410a], b'z'));
        rows.extend_from_slice(&[0xff, 0xff, b'\n']);
        for options in [WalkOptions::default(), strict.clone()] {
            let r = walk(Cursor::new(single_column_file(code, &rows)), &options).unwrap();
            assert!(matches!(r.end, WalkEnd::Complete), "{code}");
            assert!(r.warnings.is_empty(), "{code}: {:?}", r.warnings);
            let p = &r.sections[0].parts[0];
            assert_eq!(
                (p.rows.rows, p.rows.end_marker),
                (4, EndMarker::FfFf),
                "{code}"
            );
            assert_eq!(p.rows.nulls, 1);
            assert!(!p.rows.e2a_no_rows);
            let l = &p.rows.long[0];
            assert_eq!(
                (
                    l.column,
                    l.values,
                    l.chained,
                    l.largest,
                    l.above_32000,
                    l.zero_pieces
                ),
                (1, 3, 1, 32_001, 1, 0),
                "{code}"
            );
        }
        // the row starting with `0a 41` alone, written as the first row: also read, not "empty"
        let mut rows = row_value(&[0x410a], b'z');
        rows.extend_from_slice(&[0xff, 0xff, b'\n']);
        let r = walk_bytes(single_column_file(code, &rows)).unwrap();
        assert_eq!(r.sections[0].parts[0].rows.rows, 1, "{code}");
        assert!(r.warnings.is_empty());
    }
}
