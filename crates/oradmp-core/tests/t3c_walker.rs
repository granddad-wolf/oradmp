/// exp.md 6.6, session 9: T_LONG row 3 and T_LONGRAW row 2 are `9c 80` + 156 bytes, 3 x (`19 9f` + 7961),
/// `19 1f` + 7961 (156 + 4 x 7961 = 32,000), the first piece at 0x2288 (18c) / 0x2289 (11g) and, for
/// T_LONGRAW, 0xa0ea / 0xa0ec; the pieces of T_LONG at 0x2326, 0x4241, 0x615c, 0x8077 (18c; +1 for 11g); the end
/// of rows `ff ff 0a` behind the last piece at 0x9f92 / 0x9f93. T_LONG_EMPTY is empty by [E2] on 18c (the LF at
/// 0x11ee2, `0a 54` > 10) and by [E1] on 11g (`ff ff` at 0x11f47); T_FRAME follows at 0x11ee3 / 0x11f4a.
#[test]
fn b_long_exp_direct_has_chains_of_five_pieces_and_t_frame_follows() {
    for (v, d, long_first, raw_first, empty_end, empty_marker, frame_at) in [
        (
            "18c",
            0u64,
            0x2288u64,
            0xa0eau64,
            0x11ee2u64,
            EndMarker::LfOnly,
            0x11ee3u64,
        ),
        ("11g", 1, 0x2289, 0xa0ec, 0x11f47, EndMarker::FfFf, 0x11f4a),
    ] {
        let file = format!("{v}/long_exp_direct_{v}.dmp");
        let bytes = bytes_of(&file);
        let r = walk_rel(&file, &WalkOptions::default());
        assert!(matches!(r.end, WalkEnd::Complete), "{v}");
        assert!(r.warnings.is_empty(), "{v}: {:?}", r.warnings);
        assert_eq!(
            names(&r),
            ["T_LONG", "T_LONGRAW", "T_LONG_EMPTY", "T_FRAME"],
            "{v}"
        );

        // the chains, read by the test's own reader at the offsets of exp.md 6.6
        let expect_sizes = [0x809cu16, 0x9f19, 0x9f19, 0x9f19, 0x1f19];
        for (first, rel_pieces) in [
            (
                long_first,
                [
                    0u64,
                    0x2326 - 0x2288,
                    0x4241 - 0x2288,
                    0x615c - 0x2288,
                    0x8077 - 0x2288,
                ],
            ),
            (
                raw_first,
                [0, 158, 158 + 7963, 158 + 2 * 7963, 158 + 3 * 7963],
            ),
        ] {
            let ps = pieces_at(&bytes, first);
            assert_eq!(
                ps.iter().map(|p| p.0).collect::<Vec<_>>(),
                expect_sizes,
                "{v}"
            );
            assert_eq!(
                ps.iter().map(|p| p.1 - first).collect::<Vec<_>>(),
                rel_pieces,
                "{v}"
            );
            let total: u32 = ps.iter().map(|p| u32::from(p.0 & 0x7fff)).sum();
            assert_eq!(total, 156 + 4 * 7961);
        }

        // T_LONG: 3 rows; the L column (3rd in INSERT INTO order: ID, V, L) has 2 values, one chained
        let t_long = &r.sections[0].parts[0];
        assert_eq!(t_long.rows.rows, 3, "{v}");
        let ls = &t_long.rows.long;
        assert_eq!(ls.len(), 1);
        assert_eq!(
            (
                ls[0].column,
                ls[0].values,
                ls[0].chained,
                ls[0].largest,
                ls[0].above_32000
            ),
            (3, 2, 1, 32_000, 0),
            "{v}"
        );
        // the walker consumed the chain exactly: `ff ff` stands behind the last piece (0x8077 + 2 + 7961)
        assert_eq!(t_long.rows.end_marker, EndMarker::FfFf);
        assert_eq!(
            t_long.rows.end_marker_offset,
            long_first + 0x8077 - 0x2288 + 2 + 7961,
            "{v}"
        );
        assert_eq!(t_long.rows.end_marker_offset, 0x9f92 + d, "{v}");

        // T_LONGRAW: 2 rows, LR is column 2
        let t_raw = &r.sections[1].parts[0];
        assert_eq!(t_raw.rows.rows, 2, "{v}");
        let ls = &t_raw.rows.long;
        assert_eq!(
            (
                ls[0].column,
                ls[0].values,
                ls[0].chained,
                ls[0].largest,
                ls[0].above_32000
            ),
            (2, 2, 1, 32_000, 0),
            "{v}"
        );
        assert_eq!(
            t_raw.rows.end_marker_offset,
            raw_first + 158 + 3 * 7963 + 2 + 7961,
            "{v}"
        );

        // T_LONG_EMPTY: no rows, by [E2] (18c) or [E1] (11g)
        let empty = &r.sections[2].parts[0];
        assert_eq!(empty.rows.rows, 0, "{v}");
        assert_eq!(empty.rows.end_marker, empty_marker, "{v}");
        assert_eq!(empty.rows.end_marker_offset, empty_end, "{v}");
        assert!(!empty.rows.e2a_no_rows, "E2 decides, not E2a ({v})");
        assert!(empty.rows.long.iter().all(|l| l.values == 0));

        // T_FRAME follows, byte-identical to `t_frame_exp_direct_<v>` (rule T8): the walk is in step
        let frame = &r.sections[3];
        assert_eq!(frame.table_line_offset, frame_at, "{v}");
        assert_eq!(frame.parts[0].rows.rows, 7);
        let reference = walk_rel(
            &format!("{v}/t_frame_exp_direct_{v}.dmp"),
            &WalkOptions::default(),
        );
        let range = |rep: &WalkReport, i: usize| {
            let s = &rep.sections[i];
            let end = s.parts.last().unwrap().rows.rows_end_offset;
            usize::try_from(s.table_line_offset).unwrap()..usize::try_from(end).unwrap()
        };
        let reference_bytes = bytes_of(&format!("{v}/t_frame_exp_direct_{v}.dmp"));
        assert_eq!(
            bytes[range(&r, 3)],
            reference_bytes[range(&reference, 0)],
            "{v}"
        );
    }
}

