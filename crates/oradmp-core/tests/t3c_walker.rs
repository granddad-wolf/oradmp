/// Offsets of the second piece and of the first piece of T_LONG row 3 in `long_exp_direct_<v>`
/// (exp.md 6.6): 0x2288 / 0x2326 on 18c, one more on 11g.
fn long_direct(v: &str) -> (Vec<u8>, u64, u64) {
    let d = u64::from(v == "11g");
    (
        bytes_of(&format!("{v}/long_exp_direct_{v}.dmp")),
        0x2288 + d,
        0x2326 + d,
    )
}

#[test]
fn d_a_later_piece_from_0xfff0_and_a_first_u16_of_zero_are_framing() {
    for v in ["18c", "11g"] {
        let (good, first, second) = long_direct(v);
        assert_eq!(u16_at(&good, first), 0x809c);
        assert_eq!(u16_at(&good, second), 0x9f19);
        // a piece u16 `f0 ff` (and the others up to `ff ff`)
        for bad in [0xfff0u16, 0xfffc, 0xfffe, 0xffff] {
            let mut b = good.clone();
            put_u16(&mut b, second, bad);
            let e = walk_bytes(b).unwrap_err();
            assert_eq!(
                (e.code, e.offset, e.table, e.row, e.column, e.length),
                (
                    ErrorCode::Framing,
                    Some(second),
                    Some(1),
                    Some(3),
                    Some(3),
                    Some(u64::from(bad))
                ),
                "{v} {bad:#x}"
            );
        }
        // 0x7fef with the flag (0xffef) is a piece of 32,751 bytes: not an error by itself (it only
        // misframes what follows); the largest allowed piece is read by length
        // a first u16 of 0
        let mut b = good.clone();
        put_u16(&mut b, first, 0);
        let e = walk_bytes(b).unwrap_err();
        assert_eq!(
            (e.code, e.offset, e.table, e.row, e.column),
            (ErrorCode::Framing, Some(first), Some(1), Some(3), Some(3)),
            "{v}"
        );
        // a first u16 of 0xfff0..=0xfffd and `ff ff` in the field of a chain column
        for bad in [0xfff0u16, 0xfffd, 0xffff] {
            let mut b = good.clone();
            put_u16(&mut b, first, bad);
            let e = walk_bytes(b).unwrap_err();
            assert_eq!(
                (e.code, e.offset),
                (ErrorCode::Framing, Some(first)),
                "{v} {bad:#x}"
            );
        }
    }
}

#[test]
fn d_a_piece_of_length_zero_gives_one_untested_layout_warning_per_column_and_is_read_by_the_formula(
) {
    for v in ["18c", "11g"] {
        let (good, first, second) = long_direct(v);
        let reference = walk_bytes(good.clone()).unwrap();
        assert!(reference.warnings.is_empty());
        let last_piece = first + (0x8077 - 0x2288);
        let end_of_data = last_piece + 2 + 7961; // where `ff ff` stands
        assert_eq!(u16_at(&good, last_piece), 0x1f19);
        let pos = |o: u64| usize::try_from(o).unwrap();

        // (1) `00 80` (zero bytes, more follows) inserted before piece 2
        let mut b = good.clone();
        insert_keeping_size(&mut b, pos(second), &[0x00, 0x80]);
        let r = walk_bytes(b).unwrap();
        assert!(matches!(r.end, WalkEnd::Complete), "{v}");
        assert_eq!(warning_codes(&r), [WarningCode::UntestedLayout], "{v}");
        let w = &r.warnings[0];
        assert_eq!(
            (w.offset, w.table, w.column, w.row),
            (Some(second), Some(1), Some(3), Some(3)),
            "{v}"
        );
        let l = &r.sections[0].parts[0].rows.long[0];
        assert_eq!((l.values, l.chained, l.largest), (2, 1, 32_000), "{v}");
        assert_eq!(l.zero_pieces, 1);
        assert_eq!(l.first_zero_piece, Some((3, second)));
        // the rest of the file is read as before: the same rows and 4 more tables walked
        assert_eq!(
            r.parts().map(|p| p.rows.rows).collect::<Vec<_>>(),
            reference.parts().map(|p| p.rows.rows).collect::<Vec<_>>()
        );

        // (2) a final `00 00` piece: the last piece's bit 0x8000 set and a terminating piece of length 0
        let mut b = good.clone();
        put_u16(&mut b, last_piece, 0x9f19);
        insert_keeping_size(&mut b, pos(end_of_data), &[0x00, 0x00]);
        let r = walk_bytes(b.clone()).unwrap();
        assert_eq!(warning_codes(&r), [WarningCode::UntestedLayout], "{v}");
        assert_eq!(r.warnings[0].offset, Some(end_of_data), "{v}");
        assert_eq!(r.sections[0].parts[0].rows.long[0].zero_pieces, 1);

        // (3) both in one column of one section: one warning (once per column), the first offset
        let mut b2 = b;
        insert_keeping_size(&mut b2, pos(second), &[0x00, 0x80]);
        let r = walk_bytes(b2).unwrap();
        assert_eq!(warning_codes(&r), [WarningCode::UntestedLayout], "{v}");
        assert_eq!(r.warnings[0].offset, Some(second), "{v}");
        let l = &r.sections[0].parts[0].rows.long[0];
        assert_eq!((l.zero_pieces, l.largest), (2, 32_000), "{v}");
    }
}

