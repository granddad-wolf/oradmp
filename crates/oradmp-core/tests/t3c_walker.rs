#[test]
fn d_a_conventional_long_raw_field_starting_fb_ff_or_fc_ff_is_unsupported_layout_with_the_table_named(
) {
    for v in ["18c", "11g"] {
        let file = format!("{v}/long_exp_{v}.dmp");
        let good = bytes_of(&file);
        let r = walk_rel(&file, &WalkOptions::default());
        // T_LONGRAW (section 2) row 2: ID `02 00 c1 03`, then LR `00 7d` + 32,000 bytes (exp.md 6.6)
        let part = &r.sections[1].parts[0];
        let row1 = 4 + 4 + 2; // ID, LR = 00 ff, row end
        let at = part.header.rows_offset + row1 + 4;
        assert_eq!(u16_at(&good, at), 32_000, "{v}");
        for len in [0xfffbu16, 0xfffc] {
            let mut b = good.clone();
            put_u16(&mut b, at, len);
            let r = walk_bytes(b).unwrap();
            let e = stopped(&r);
            assert_eq!(
                e.message,
                "conventional LONG or LONG RAW field starting 0xfffb or 0xfffc, not in the fixtures [R8]"
            );
            assert_eq!(
                (e.code, e.offset, e.table, e.row, e.column, e.length),
                (
                    ErrorCode::UnsupportedLayout,
                    Some(at),
                    Some(2),
                    Some(2),
                    Some(2),
                    Some(u64::from(len))
                ),
                "{v} {len:#x}"
            );
            // the table is named from its TABLE line; the earlier table is readable
            let st = r.stopped_section.as_ref().unwrap();
            assert_eq!(
                (st.ordinal, st.name_raw.as_slice()),
                (2, &b"T_LONGRAW"[..]),
                "{v}"
            );
            assert_eq!(names(&r), ["T_LONG"], "{v}");
            assert_eq!(r.sections[0].parts[0].rows.rows, 3);
        }
        // T-19b (ADR-99 item 1): the other lengths that stopped a LONG RAW in T-19 (0x8000, 0xffef, `f0 ff`, `fd ff`)
        // are readable forms now; the patched copy misframes what follows (a hard error, or a different later
        // result), but the field itself is never refused with `E-UNSUPPORTED-LAYOUT` at its u16
        for len in [0x8000u16, 0xffef, 0xfff0, 0xfffd] {
            let mut b = good.clone();
            put_u16(&mut b, at, len);
            match walk_bytes(b) {
                Err(e) => assert_ne!(e.code, ErrorCode::UnsupportedLayout, "{v} {len:#x}"),
                Ok(r) => {
                    if let WalkEnd::Stopped(e) = &r.end {
                        assert_ne!(e.offset, Some(at), "{v} {len:#x}");
                    }
                }
            }
        }
        // a conventional LONG below 0x8000 is a plain length: 0x7fff is read (and misframes only what
        // follows, here a Framing error later), the field itself is not refused
        let mut b = good.clone();
        put_u16(&mut b, at, 0x7fff);
        let r = walk_bytes(b);
        if let Err(e) = &r {
            assert_ne!(e.code, ErrorCode::UnsupportedLayout);
        }
        // a VARCHAR2 length from 0x8000 is not a LONG: only LONG / LONG RAW columns are checked
    }
}

