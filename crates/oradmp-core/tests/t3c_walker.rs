mod common;

use std::io::Cursor;
use std::path::{Path, PathBuf};

use oradmp_core::exp::items::{walk, walk_path, WalkEnd, WalkOptions, WalkReport};
use oradmp_core::exp::rows::EndMarker;
use oradmp_core::{Error, ErrorCode, WarningCode};

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../corpus/fixtures")
}

fn bytes_of(rel: &str) -> Vec<u8> {
    std::fs::read(fixtures().join(rel)).unwrap()
}

fn walk_bytes(b: Vec<u8>) -> oradmp_core::Result<WalkReport> {
    walk(Cursor::new(b), &WalkOptions::default())
}

fn walk_rel(rel: &str, options: &WalkOptions) -> WalkReport {
    walk_path(&fixtures().join(rel), options).unwrap_or_else(|e| panic!("{rel}: {e}"))
}

fn find_bytes(hay: &[u8], needle: &[u8]) -> usize {
    hay.windows(needle.len()).position(|w| w == needle).unwrap()
}

fn u16_at(b: &[u8], at: u64) -> u16 {
    let at = usize::try_from(at).unwrap();
    u16::from_le_bytes([b[at], b[at + 1]])
}

fn put_u16(b: &mut [u8], at: u64, v: u16) {
    let at = usize::try_from(at).unwrap();
    b[at..at + 2].copy_from_slice(&v.to_le_bytes());
}

/// Inserts bytes and takes the same number of zero bytes off the end (the files end in zero fill), so the
/// size stays a multiple of RECORDLENGTH and `W-FILE-SIZE` does not appear.
fn insert_keeping_size(b: &mut Vec<u8>, at: usize, ins: &[u8]) {
    b.splice(at..at, ins.iter().copied());
    let cut = b.len() - ins.len();
    assert!(b[cut..].iter().all(|&x| x == 0), "the fill is too short");
    b.truncate(cut);
}

fn warning_codes(r: &WalkReport) -> Vec<WarningCode> {
    r.warnings.iter().map(|w| w.code).collect()
}

fn stopped(r: &WalkReport) -> &Error {
    match &r.end {
        WalkEnd::Stopped(e) => e,
        WalkEnd::Complete => panic!("the walk was not stopped"),
    }
}

fn names(r: &WalkReport) -> Vec<String> {
    r.sections
        .iter()
        .map(|s| String::from_utf8(s.name_raw.clone()).unwrap())
        .collect()
}

/// (first u16 of each piece, offset of the u16) of the chain that starts at `at`, read from the bytes by the
/// rule of [R2] (the test's own reader, not the walker's).
fn pieces_at(b: &[u8], at: u64) -> Vec<(u16, u64)> {
    let mut out = Vec::new();
    let mut p = at;
    loop {
        let n = u16_at(b, p);
        out.push((n, p));
        p += 2 + u64::from(n & 0x7fff);
        if n & 0x8000 == 0 {
            return out;
        }
    }
}

