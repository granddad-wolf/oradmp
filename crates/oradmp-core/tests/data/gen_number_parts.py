#!/usr/bin/env python3
"""Generates tests/data/value_parts.tsv for tests/t4_values.rs from the Analyst's tools.

Run (read-only on the fixtures, writes one TSV next to this script, nothing else):

    cd docs/formats/tools && uv run ../../../crates/oradmp-core/tests/data/gen_number_parts.py

One line per binary part of every `*_exp_*.dmp` fixture (229 files): where its rows start, the path, the row
count, the column type codes and, as the independent expectation of the Rust field reader in the test, the
number of non-NULL NUMBER fields (type code 2) and the SHA-256 over those fields in file order, row after row,
each serialised as one length byte followed by its bytes. Sources: exp_parse.parse() (tables: rows_off, direct,
cols[].type, rows[].fields; the pieces of a direct-path LONG chain are already assembled there). The generator
asserts the total of 86,236 NUMBER fields (rules v3.9, tools/num_decode.py step 3: "86236 decoded and re-encoded", run in T-19b) and 229 files.
"""
import glob
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.abspath(os.path.join(HERE, "../../../../docs/formats/tools"))
sys.path.insert(0, TOOLS)
from exp_parse import parse  # noqa: E402

FIX = os.path.abspath(os.path.join(HERE, "../../../../corpus/fixtures"))


def main() -> None:
    out = ["# value_parts.tsv: generated by gen_number_parts.py from docs/formats/tools (exp_parse.py). "
           "Do not edit by hand.",
           "file\trows_off\tdirect\trows\ttypes\tnumber_fields\tnumber_sha256"]
    files = 0
    total = 0
    parts = 0
    for d in ("18c", "11g", "11g-cp1251"):
        for f in sorted(glob.glob(os.path.join(FIX, d, "*_exp_*.dmp"))):
            r = parse(f)
            assert not r["problems"], (f, r["problems"])
            files += 1
            for t in r["tables"]:
                types = [c["type"] for c in t["cols"]]
                nc = [i for i, ty in enumerate(types) if ty == 2]
                h = hashlib.sha256()
                n = 0
                for _ro, row in t["rows"]:
                    for ci in nc:
                        v = row[ci][1]
                        if v is not None:
                            h.update(bytes([len(v)]) + v)
                            n += 1
                total += n
                parts += 1
                out.append("\t".join([f"{d}/{os.path.basename(f)}", str(t["rows_off"]), "1" if t["direct"] else "0",
                                      str(len(t["rows"])), ",".join(map(str, types)), str(n), h.hexdigest()]))
    assert files == 229, files
    assert total == 86236, total
    print(f"{files} files, {parts} parts, {total} NUMBER fields")
    with open(os.path.join(HERE, "value_parts.tsv"), "w") as o:
        o.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
