"""Task T-13 (b): the value-level check again through pyarrow, for every table of every ``_exp_`` fixture.

For each table the pyarrow table (``Dump.read_table(...).read_all()``) equals what the Rust core read: the digest
``_core.digest`` computes from the core's own batches, against the same canonical form recomputed from the pyarrow
table (``conftest.table_digest``). The Rust side is checked against the truth files by ``t10_truth.rs``; this
test proves the hand-over keeps every cell of every file (no truth text is repeated here).

A table that fails under the default options must be one of the documented failures (``t11_strict.rs``
``DOCUMENTED``, ``t10_truth.rs``): T_DATE and T_TS (``E-BAD-DATETIME``), T_INTERVAL2 (``E-BAD-INTERVAL``),
T_NUM (``E-NUMBER-OVERFLOW``), each with the code listed there, and both sides must fail with that code. Those
tables are compared again under ``on_value_error="null"``. One test per version folder.
"""

from __future__ import annotations

from pathlib import Path

import oradmp
import pytest
from conftest import FIXTURES, table_digest
from oradmp import _core

pytestmark = pytest.mark.filterwarnings("ignore::oradmp.OradmpWarning")

# t11_strict.rs DOCUMENTED, stage "read": table -> error code under the default options
DOCUMENTED_FAILURES = {
    "T_DATE": "E-BAD-DATETIME",
    "T_INTERVAL2": "E-BAD-INTERVAL",
    "T_NUM": "E-NUMBER-OVERFLOW",
    "T_TS": "E-BAD-DATETIME",
}
FOLDERS = ["18c", "11g", "11g-cp1251"]
CATALOG = FIXTURES.parent.parent / "tests" / "golden" / "exp_catalog.tsv"


def catalog_tables(folder: str) -> list[str]:
    """The table of every section of the folder's ``_exp_`` files, from ``tests/golden/exp_catalog.tsv``
    (generated by ``gen_exp_catalog.py`` from the Analyst's ``exp_parse.py``, independent of the reader)."""
    rows = [
        line.split("\t")
        for line in CATALOG.read_text().splitlines()
        if line and not line.startswith("#") and not line.startswith("file\t")
    ]
    return [r[2] for r in rows if r[0].startswith(folder + "/") and "_exp_" in r[0]]


def catalog_rows(folder: str, name: str) -> dict[int, int]:
    """Section ordinal -> row count of one file, from the golden catalog (the Analyst's parse, not the reader)."""
    out: dict[int, int] = {}
    for line in CATALOG.read_text().splitlines():
        f = line.split("\t")
        if len(f) > 7 and f[0] == f"{folder}/{name}":
            out[int(f[1])] = int(f[7])
    return out


def exp_files(folder: str) -> list[Path]:
    return sorted(p for p in (FIXTURES / folder).iterdir() if "_exp_" in p.name and p.suffix == ".dmp")


def check_file(path: Path, failed: dict[str, int]) -> int:
    """Compares every table of one file; returns the number of tables read."""
    compared = 0
    golden_rows = catalog_rows(path.parent.name, path.name)
    assert golden_rows, path
    core = _core.open(str(path), {})
    with oradmp.open(str(path)) as dump:
        for t in dump.tables:
            for policy in ("raise", "null"):
                want_error: str | None
                opts = {"on_value_error": policy, "on_number_overflow": "round"}
                try:
                    want = core.digest(t.ordinal, opts)
                except oradmp.OradmpError as e:
                    assert policy == "raise", (path.name, t.name, policy, e)
                    want_error = e.code
                else:
                    want_error = None
                try:
                    with dump.read_table(t.ordinal, on_value_error=policy) as r:
                        table = r.read_all()
                except oradmp.OradmpError as e:
                    assert want_error == e.code, (path.name, t.name, "Python and Rust disagree", e)
                    assert DOCUMENTED_FAILURES.get(t.name) == e.code, (path.name, t.name, e)
                    failed[t.name] = failed.get(t.name, 0) + 1
                    continue  # the same table is compared again under "null"
                assert want_error is None, (path.name, t.name, "Rust failed, Python did not")
                assert table_digest(table) == want, (path.name, t.name, policy)
                # every row arrives under every policy (a failing value is NULL, the row stays): the golden count
                assert table.num_rows == golden_rows[t.ordinal], (path.name, t.name, policy)
                if policy == "raise":
                    compared += 1
                    break
                assert t.name in DOCUMENTED_FAILURES  # reached only after a documented failure
    return compared


@pytest.mark.parametrize("folder", FOLDERS)
def test_every_table_of_every_exp_file_equals_the_rust_read(folder: str) -> None:
    files = exp_files(folder)
    assert files
    failed: dict[str, int] = {}
    read_ok = sum(check_file(f, failed) for f in files)
    sections = catalog_tables(folder)
    documented = [t for t in sections if t in DOCUMENTED_FAILURES]
    # every section of the catalog was compared: read in full, or failed with its documented code and then
    # compared under on_value_error="null" (check_file asserts that digest too)
    assert read_ok + len(documented) == len(sections), (read_ok, len(documented), len(sections))
    assert sum(failed.values()) == len(documented), (failed, len(documented))
    for name in DOCUMENTED_FAILURES:
        assert failed.get(name, 0) == documented.count(name), name
