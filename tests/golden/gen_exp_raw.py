#!/usr/bin/env python3
"""Generates exp_raw.tsv, the raw manifest of the legacy exp fixtures (architecture 8.2 (a), tasks T-2 and T-3b).

Run once (read-only on the fixtures; the Analyst's tool is imported, not copied):

    cd docs/formats/tools && python3 -I ../../../tests/golden/gen_exp_raw.py > ../../../tests/golden/exp_raw.tsv

Source of every number: `exp_parse.parse()` of docs/formats/tools/exp_parse.py (default rules: generic items,
empty tables by the text rule) over every `*_exp_*.dmp` of corpus/fixtures/{18c,11g,11g-cp1251}:
table sections and binary parts as counted by the catalog (T-19b: 229 files, 436 sections, 450 parts; T-2 had 289
lines of the tables before the old X1 stop).

One line per binary part (`INSERT INTO` line), tab separated; in file order. A file that has a column type
code outside rule T5 (the 16 codes of v3.4) makes the generator fail.

Columns:
  file       folder/name of the fixture
  ordinal    1-based ordinal of the table section in the file (sections without INSERT INTO count)
  part       1-based index of the part in its section (1 for an unpartitioned table)
  table      name as written in the TABLE line; bytes outside 0x20..0x7e and the backslash as \\xNN
  partition  name of the PARTITION line, or of the COMPARTITION line that encloses the part; `-` if none
  subpart    name of the SUBPARTITION line; `-` if none
  ncols      number of columns
  cols       `type:maxlen` of every column, separated by commas (maxlen is the u16 of the descriptor)
  path       conv (flag 0) or direct (flag 1)
  rows       number of rows
  nulls      number of NULL fields (ff fe)
  sha256     SHA-256 of the raw fields, serialised as: per row, per column in order,
               a NULL as ff ff ff ff;
               a direct-path LONG / LONG RAW field (type 8 or 24, path flag 1; a chain of pieces, also of one
               piece): fd ff ff ff, then per piece its length without bit 0x8000 as u32 little-endian and its
               bytes as they stand, then fc ff ff ff;
               a conventional-path LONG in the chunked `fd ff` form (T-19, ADR-95 item 10; `long_chunks` of
               exp_parse.py): fb ff ff ff, then per data chunk its length as u32 little-endian and its bytes,
               then fa ff ff ff (the final `00 00` chunk is not serialised);
               a conventional-path LONG / LONG RAW in the 4-byte-length form (b) (T-19b, ADR-99 item 5, rule R2 v3.9;
               `long_fa` of exp_parse.py): f9 ff ff ff, then n as u32 little-endian and the n value bytes (the six
               framing bytes `fa ff`, n, `00 00` are not serialised), so that a golden line tells the forms apart;
               any other field: its length (u32 little-endian) followed by its bytes exactly as in the file
               (a conventional LONG from 0x8000 to 0xfff0 is such a field);
             nothing between rows or fields, nothing at the end
  lob_values number of LOB values of the part (T-3b; 0 for a table without a LOB column)
  lob_bytes  sum of their stored byte lengths (n of a short value, T of a long one)
  lob_sha256 SHA-256 over the LOB values in file order, each as its stored length (u64 little-endian)
             followed by its bytes (the chunks of a long value joined); `-` if the part has no LOB column
  long       for each LONG / LONG RAW column of the part: `position:values:sha256` (1-based file position,
             number of non-NULL values, SHA-256 over the **assembled** values in row order: a NULL is 8 bytes
             ff, any other value its total length as u64 little-endian and its bytes, pieces joined),
             separated by commas; `-` if the part has none. The conventional and the direct export of one
             table give equal digests.
"""
import glob
import hashlib
import os
import struct
import sys

TOOLS = os.getcwd()
sys.path.insert(0, TOOLS)
from exp_parse import parse  # noqa: E402

FIX = os.path.abspath(os.path.join(TOOLS, "../../../corpus/fixtures"))
SUPPORTED = {1, 2, 8, 12, 23, 24, 69, 96, 112, 113, 180, 181, 182, 183, 208, 231}  # rule T5, v3.4


def esc(b: bytes) -> str:
    return "".join(chr(c) if 0x20 <= c <= 0x7E and c != 0x5C else "\\x%02x" % c for c in b)


def main() -> None:
    print("# exp_raw.tsv: generated by tests/golden/gen_exp_raw.py from docs/formats/tools/exp_parse.py.")
    print("# See the docstring of the generator for the columns and the serialisation hashed in sha256.")
    print("file\tordinal\tpart\ttable\tpartition\tsubpart\tncols\tcols\tpath\trows\tnulls\tsha256\t"
          "lob_values\tlob_bytes\tlob_sha256\tlong")
    files = sorted(glob.glob(os.path.join(FIX, "*", "*_exp_*.dmp")))
    for f in files:
        r = parse(f)
        assert not r["problems"], (f, r["problems"])
        data = open(f, "rb").read()
        name = os.path.relpath(f, FIX)
        seen: dict = {}
        for t in r["tables"]:
            assert all(c["type"] in SUPPORTED for c in t["cols"]), (f, t["name"])
            sec = t.get("section", t)
            ordinal = r["sections"].index(sec) + 1
            part = seen[ordinal] = seen.get(ordinal, 0) + 1
            chains = {(ri, fo): plens for ri, fo, plens in t.get("long_pieces", [])}
            chunked = {(ri, fo): clens for ri, fo, clens in t.get("long_chunks", [])}
            four = {(ri, fo): n for ri, fo, n in t.get("long_fa", [])}
            h = hashlib.sha256()
            nulls = 0
            for ri, (_off, row) in enumerate(t["rows"]):
                for fo, v in row:
                    if v is None:
                        nulls += 1
                        h.update(b"\xff\xff\xff\xff")
                    elif (ri, fo) in chains:
                        h.update(b"\xfd\xff\xff\xff")
                        q = fo
                        for n in chains[(ri, fo)]:
                            ln = n & 0x7FFF
                            h.update(struct.pack("<I", ln) + data[q + 2:q + 2 + ln])
                            q += 2 + ln
                        h.update(b"\xfc\xff\xff\xff")
                    elif (ri, fo) in chunked:
                        h.update(b"\xfb\xff\xff\xff")
                        q = fo + 2
                        for n in chunked[(ri, fo)]:
                            if n == 0:
                                break
                            h.update(struct.pack("<I", n) + data[q + 2:q + 2 + n])
                            q += 2 + n
                        h.update(b"\xfa\xff\xff\xff")
                    elif (ri, fo) in four:
                        h.update(b"\xf9\xff\xff\xff" + struct.pack("<I", four[(ri, fo)]) + v)
                    else:
                        h.update(struct.pack("<I", len(v)) + v)
            lobs = t["lob_values"]
            lob_sha = "-"
            if t["lob"]:
                lh = hashlib.sha256()
                for _ri, _ci, _vo, buf, _form, _lens in lobs:
                    lh.update(struct.pack("<Q", len(buf)) + buf)
                lob_sha = lh.hexdigest()
            longs = []
            for ci, c in enumerate(t["cols"]):
                if c["type"] not in (8, 24):
                    continue
                lh = hashlib.sha256()
                count = 0
                for _off, row in t["rows"]:
                    v = row[ci][1]
                    if v is None:
                        lh.update(b"\xff" * 8)
                    else:
                        count += 1
                        lh.update(struct.pack("<Q", len(v)) + v)
                longs.append("%d:%d:%s" % (ci + 1, count, lh.hexdigest()))
            cols = ",".join("%d:%d" % (c["type"], c["len"]) for c in t["cols"])
            print("\t".join([name, str(ordinal), str(part), esc(t["name"].encode("latin-1")),
                             esc(t["partition"].encode("latin-1")) if t["partition"] is not None else "-",
                             esc(t["subpartition"].encode("latin-1")) if t["subpartition"] is not None else "-",
                             str(len(t["cols"])), cols, "direct" if t["direct"] else "conv",
                             str(len(t["rows"])), str(nulls), h.hexdigest(),
                             str(len(lobs)), str(sum(len(x[3]) for x in lobs)), lob_sha,
                             ",".join(longs) if longs else "-"]))


if __name__ == "__main__":
    main()
