#!/usr/bin/env python3
"""Generates exp_catalog.tsv, the catalog golden file of the legacy exp fixtures (tasks T-3 and T-3b).

Run once (read-only on the fixtures; the Analyst's tool is imported, not copied):

    cd docs/formats/tools && python3 -I ../../../tests/golden/gen_exp_catalog.py > ../../../tests/golden/exp_catalog.tsv

Source of every number: `exp_parse.parse()` of docs/formats/tools/exp_parse.py over every `*_exp_*.dmp` of
corpus/fixtures/{18c,11g,11g-cp1251}: 229 files, 436 table sections (every section has an INSERT INTO line),
450 binary parts (T-19b). One line per table section; the offsets of every part are in the last column.

Columns, tab separated, one line per file and table section:
  file          folder/name of the fixture
  ordinal       1-based ordinal of the section (as in exp_raw.tsv)
  table         name of the TABLE line; bytes outside 0x20..0x7e and the backslash as \\xNN
  insert_name   the table name of the INSERT INTO line of the first part, same escaping
  nparts        number of binary parts
  partitioned   1 if a part has a PARTITION or COMPARTITION name, else 0
  subpartitioned 1 if a part has a SUBPARTITION name, else 0
  num_rows      rows of the table: the sum over the parts
  create_off    offset of the CREATE TABLE line (hex)
  ddl_sha256    SHA-256 of the CREATE TABLE line without its LF
  ncols         number of column names of the INSERT INTO line of the first part
  names         the column names of the first part in file order, joined by `|` (escaped as above; a `|` in
                a name never occurs in the fixtures)
  parts         the parts, joined by `;`; each `insert_off,rows_off,rows_end_off,marker,rows` with the three
                offsets in hex, marker `ffff` (ff ff before the LF) or `lf` (direct path, LF only), and the
                number of rows
"""
import glob
import hashlib
import os
import re
import sys

TOOLS = os.getcwd()
sys.path.insert(0, TOOLS)
from exp_parse import parse  # noqa: E402

FIX = os.path.abspath(os.path.join(TOOLS, "../../../corpus/fixtures"))
SUPPORTED = {1, 2, 8, 12, 23, 24, 69, 96, 112, 113, 180, 181, 182, 183, 208, 231}  # rule T5, v3.4


def esc(b: bytes) -> str:
    return "".join(chr(c) if 0x20 <= c <= 0x7E and c != 0x5C else "\\x%02x" % c for c in b)


def main() -> None:
    print("# exp_catalog.tsv: generated by tests/golden/gen_exp_catalog.py from docs/formats/tools/exp_parse.py.")
    print("# See the docstring of the generator for the columns.")
    print("file\tordinal\ttable\tinsert_name\tnparts\tpartitioned\tsubpartitioned\tnum_rows\tcreate_off\tddl_sha256\tncols\tnames\tparts")
    for f in sorted(glob.glob(os.path.join(FIX, "*", "*_exp_*.dmp"))):
        r = parse(f)
        assert not r["problems"], (f, r["problems"])
        name = os.path.relpath(f, FIX)
        items = r["items"]
        by_section: dict = {}
        for t in r["tables"]:
            assert all(c["type"] in SUPPORTED for c in t["cols"]), (f, t["name"])
            by_section.setdefault(id(t.get("section", t)), []).append(t)
        for sec in r["sections"]:
            parts = by_section[id(sec)]
            ordinal = r["sections"].index(sec) + 1
            first = parts[0]
            m = re.fullmatch(rb'INSERT INTO "([^"]*)" \((.*)\) VALUES \((.*)\)', first["insert_raw"])
            assert m, first["insert_raw"]
            names = re.findall(rb'"([^"]*)"', m.group(2))
            assert len(names) == len(m.group(3).split(b", ")) == len(first["cols"])
            # the CREATE TABLE item is the one after the TABLE line of the section
            idx = next(i for i, it in enumerate(items) if it["off"] == sec["table_off"])
            create = items[idx + 1]
            assert create["kind"] == "line" and create["text"].startswith("CREATE TABLE ")
            plist = []
            for t in parts:
                marker = "lf" if t["end_marker"] is None else "ffff"
                plist.append("%x,%x,%x,%s,%d" % (t["insert_off"], t["rows_off"], t["rows_end"] + 1, marker,
                                                 len(t["rows"])))
            print("\t".join([
                name, str(ordinal), esc(sec["name"].encode("latin-1")), esc(m.group(1)),
                str(len(parts)), "1" if any(t["partition"] is not None for t in parts) else "0",
                "1" if any(t["subpartition"] is not None for t in parts) else "0",
                str(sum(len(t["rows"]) for t in parts)),
                "%x" % create["off"], hashlib.sha256(create["raw"]).hexdigest(),
                str(len(names)), "|".join(esc(n) for n in names), ";".join(plist)]))


if __name__ == "__main__":
    main()
